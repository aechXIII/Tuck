import { expect, test } from "@playwright/test";
import { healthyBackendFixture, installFakeBackend } from "../fixtures/fake-backend";

for (const width of [1240, 960]) {
  test(`saved LUT search, keyboard selection and clear history at ${width}`, async ({page}) => {
    await page.setViewportSize({width,height:width === 960 ? 640 : 800});
    await page.emulateMedia({reducedMotion:"reduce"});
    const fixture = healthyBackendFixture();
    const entries = [{path:"C:/managed/warm.cube",name:"Warm"},{path:"C:/managed/cool.cube",name:"Cool"},
      {path:"C:/managed/long.cube",name:"Evening light — a very long descriptive filename with extra detail.cube"},
      ...Array.from({length:8},(_, index) => ({path:`C:/managed/film-${index}.cube`,name:`Film ${index + 1}`}))];
    fixture.responses.listLuts = {luts:entries};
    fixture.responses.pickLutFile = {path:""};
    fixture.responses.loadLut = {path:entries[1]!.path,name:entries[1]!.name,size:2,table_url:"http://127.0.0.1:4321/token/table",token:"t"};
    fixture.responseSequences = {clearLutHistory:[{ok:false,error:"LUT history could not be saved. Try again."},{cleared:true}]};
    await page.route("http://127.0.0.1:4321/token/table", route => route.fulfill({body:Buffer.from(new Float32Array(24).buffer),headers:{"Access-Control-Allow-Origin":"*"}}));
    await installFakeBackend(page,fixture);
    await page.goto("/");
    if (width === 960) await page.getByRole("button",{name:"Inspector",exact:true}).click();
    await page.locator("#lut-panel > summary").click();
    const trigger = page.getByRole("button",{name:/^LUT /});
    await expect(trigger).toHaveAccessibleName("LUT No LUT selected");
    const popup = page.getByRole("dialog",{name:"Saved LUTs",exact:true});
    const search = page.getByRole("combobox",{name:"Search saved LUTs",exact:true});
    const options = popup.getByRole("option");
    await trigger.focus();
    const closedRow = await page.locator(".lut-file-row").boundingBox();
    const closedImport = await page.locator("#lut-import").boundingBox();
    await expect(page.locator("#lut-import")).toHaveText("Import");
    expect(await page.locator("#lut-import").evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
    await page.keyboard.press("ArrowDown");
    await expect(search).toBeFocused();
    const openMenu = await popup.boundingBox();
    const openImport = await popup.getByRole("button",{name:"Import",exact:true}).boundingBox();
    expect(await page.locator("#lut-import").evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
    expect(Math.abs(openMenu!.y - closedRow!.y)).toBeLessThanOrEqual(1);
    expect(Math.abs(openMenu!.width - closedRow!.width)).toBeLessThanOrEqual(1);
    expect(Math.abs(openImport!.x - closedImport!.x)).toBeLessThanOrEqual(2);
    await expect(options).toHaveCount(entries.length);
    await search.fill("evening");
    await expect(options).toHaveCount(1);
    await expect(options).toHaveText(entries[2]!.name);
    await expect(popup).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(trigger).toBeFocused();
    if (width === 960) await expect(page.getByRole("button",{name:"Inspector",exact:true})).toHaveAttribute("aria-expanded","true");
    await trigger.click();
    await expect(options).toHaveCount(entries.length);
    const fits = await popup.evaluate(node => {
      const bounds = node.getBoundingClientRect();
      return bounds.top >= 0 && bounds.bottom <= innerHeight && bounds.left >= 0 && bounds.right <= innerWidth && node.scrollWidth <= node.clientWidth;
    });
    expect(fits).toBe(true);
    await search.fill("not a saved look");
    await expect(options).toHaveCount(0);
    await expect(popup.getByText("No LUTs found.",{exact:true})).toBeVisible();
    await page.keyboard.press("Enter");
    await expect(popup).toBeVisible();
    await search.fill("");
    await page.keyboard.press("ArrowDown");
    await page.keyboard.press("ArrowUp");
    await page.keyboard.press("ArrowDown");
    await page.keyboard.press("Enter");
    await expect(trigger).toHaveText("Cool");
    await expect(trigger).toHaveAccessibleName("LUT Cool");
    await expect(trigger).toBeFocused();
    await expect(page.getByLabel("Apply LUT",{exact:true})).toBeChecked();
    await trigger.click();
    await expect(popup.getByRole("option",{name:"Cool",exact:true})).toHaveAttribute("aria-selected","true");
    await popup.getByRole("button",{name:"Clear history",exact:true}).click();
    await expect(popup.getByRole("status")).toHaveText("LUT history could not be saved. Try again.");
    await expect(options).toHaveCount(entries.length);
    await expect(trigger).toHaveText("Cool");
    await expect(search).toBeFocused();
    await popup.getByRole("button",{name:"Clear history",exact:true}).click();
    await expect(popup.getByRole("status")).toHaveText("History cleared. Your current LUT stays selected.");
    await expect(options).toHaveCount(0);
    await expect(popup.getByRole("button", {name:"Remove LUT",exact:true})).toBeVisible();
    await expect(trigger).toHaveText("Cool");
    await expect(page.getByLabel("Apply LUT",{exact:true})).toBeChecked();
    await expect(popup.getByRole("button",{name:"Clear history",exact:true})).toBeDisabled();
    await expect(search).toBeFocused();
    await page.keyboard.press("Escape");
    await expect(trigger).toBeFocused();
    await page.getByLabel("Strength",{exact:true}).fill("35");
    await trigger.click();
    await expect(options).toHaveCount(0);
    await page.keyboard.press("Escape");
    const calls = await page.evaluate(() => window.__tuckFakeBackendCalls ?? []);
    expect(calls.filter(call=>call.method === "loadLut")).toHaveLength(1);
    expect(calls.filter(call=>call.method === "clearLutHistory")).toHaveLength(2);
    await trigger.click();
    await popup.getByRole("button",{name:"Import",exact:true}).click();
    await expect(popup).toBeHidden();
    await expect(page.locator(".lut-file-row > #lut-import")).toBeVisible();
    await expect(trigger).toHaveText("Cool");
    await expect(page.locator("#lut-import")).toBeFocused();
  });
}

test("the open LUT menu continues its row and lights one option, which the pointer moves", async ({page}) => {
  const fixture = healthyBackendFixture();
  fixture.responses.listLuts = {luts:[{path:"C:/managed/warm.cube",name:"Warm"},{path:"C:/managed/cool.cube",name:"Cool"},{path:"C:/managed/film.cube",name:"Film"}]};
  fixture.responses.loadLut = {path:"C:/managed/film.cube",name:"Film",size:2,table_url:"http://127.0.0.1:4321/token/table",token:"t"};
  await page.route("http://127.0.0.1:4321/token/table", route => route.fulfill({body:Buffer.from(new Float32Array(24).buffer),headers:{"Access-Control-Allow-Origin":"*"}}));
  await installFakeBackend(page,fixture);
  await page.goto("/");
  await page.locator("#lut-panel > summary").click();
  const row = page.locator(".lut-file-row");
  const closed = await row.evaluate(node => ({height: node.getBoundingClientRect().height, radius: getComputedStyle(node).borderTopLeftRadius}));
  await page.getByRole("button",{name:/^LUT /}).click();
  const popup = page.getByRole("dialog",{name:"Saved LUTs",exact:true});
  const head = await page.locator(".lut-picker-head").evaluate(node => node.getBoundingClientRect().height);
  const radius = await popup.evaluate(node => getComputedStyle(node).borderTopLeftRadius);
  expect(head).toBeCloseTo(closed.height, 0);
  expect(radius).toBe(closed.radius);
  const options = popup.getByRole("option");
  const lit = () => options.evaluateAll(rows => rows.map(row => getComputedStyle(row).backgroundColor !== "rgba(0, 0, 0, 0)"));
  const search = page.getByRole("combobox",{name:"Search saved LUTs",exact:true});
  // a click opens with nothing lit; the pointer lights a row and it goes dark when the pointer leaves
  expect(await lit()).toEqual([false, false, false]);
  await options.nth(1).hover();
  expect(await lit()).toEqual([false, true, false]);
  await page.mouse.move(5, 5);
  expect(await lit()).toEqual([false, false, false]);
  await expect(search).not.toHaveAttribute("aria-activedescendant");
  await options.nth(2).hover();
  await expect(search).toHaveAttribute("aria-activedescendant", (await options.nth(2).getAttribute("id"))!);
  await page.keyboard.press("Enter");
  await expect(popup).toBeHidden();
  await expect(page.getByRole("button",{name:/^LUT /})).toHaveAccessibleName("LUT Film");
});
